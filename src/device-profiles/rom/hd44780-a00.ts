function parseRows(spec: string): readonly number[] {
  const rows = spec.split(' ').map((bits) => Number.parseInt(bits, 2));
  return Object.freeze([...rows, 0]);
}

const TABLE = new Map<number, readonly number[]>();
for (const [code, rows] of SPECS) TABLE.set(code, parseRows(rows));
/** 0xFF: bloque completo de 5×8. */
TABLE.set(0xff, Object.freeze([31, 31, 31, 31, 31, 31, 31, 31]));

/** Glifos ROM A00 por código de carácter. */
export const HD44780_A00: ReadonlyMap<number, readonly number[]> = TABLE;

/** Representación de 7 filas usada para construir la fuente del editor. */
export function a00GlyphRows7(code: number): readonly number[] | undefined {
  const rows = TABLE.get(code);
  return rows ? rows.slice(0, 7) : undefined;
}
